class CmdReviewPrTests(unittest.TestCase):
    def _args(self, diff_file: str | None):
        argv = ["review-pr"]
        if diff_file:
            argv += ["--diff-file", diff_file]
        argv += ["--json"]
        return build_parser().parse_args(argv)

    def test_missing_diff_returns_infra_error(self) -> None:
        from app.cli.main import cmd_review_pr

        with mock.patch.dict("os.environ", {}, clear=True):
            code = cmd_review_pr(self._args(None), Path("."))
        self.assertEqual(code, 4)

    def test_unreadable_diff_returns_infra_error(self) -> None:
        from app.cli.main import cmd_review_pr

        code = cmd_review_pr(self._args("Z:/no/such/file.diff"), Path("."))
        self.assertEqual(code, 4)

    def test_empty_diff_skips_cleanly(self) -> None:
        import tempfile

        from app.cli.main import cmd_review_pr

        with tempfile.TemporaryDirectory() as tmp:
            empty = Path(tmp) / "empty.diff"
            empty.write_text("", encoding="utf-8")
            code = cmd_review_pr(self._args(str(empty)), Path(tmp))
        self.assertEqual(code, 0)


